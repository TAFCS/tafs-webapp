#!/usr/bin/env bash
# TAFSD-615. Regenerate src/features/mcp-docs/mcp-tools.generated.ts from the
# MCP server code in a tafs-backend checkout (with node_modules installed).
#   scripts/mcp-docs/sync-tools.sh ../tafs-backend
# Use a checkout of backend main: the docs describe what is deployed.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
webapp="$(cd "$here/../.." && pwd)"
backend="$(cd "${1:?usage: sync-tools.sh <tafs-backend checkout>}" && pwd)"
tmp="$backend/.mcp-docs-dump.ts"
trap 'rm -f "$tmp"' EXIT
cp "$here/dump-mcp-tools.ts" "$tmp"
json="$(cd "$backend" && TS_NODE_TRANSPILE_ONLY=1 npx ts-node -T .mcp-docs-dump.ts)"
commit="$(git -C "$backend" rev-parse --short HEAD)"
out="$webapp/src/features/mcp-docs/mcp-tools.generated.ts"
{
  echo "// GENERATED by scripts/mcp-docs/sync-tools.sh from tafs-backend $commit"
  echo "// (src/modules/mcp/mcp-tools.ts + tiles.manifest.ts). Do not edit by hand: rerun the script."
  echo "export const MCP_TOOLS_SOURCE_COMMIT = \"$commit\";"
  echo "export const MCP_GENERATED = $json as const;"
} > "$out"
echo "wrote $out from tafs-backend $commit"
