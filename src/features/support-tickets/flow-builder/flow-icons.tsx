// Web glyphs for the shared flow icon names (Material names, which the apps use as-is).
export const FLOW_ICON_GLYPHS: Record<string, LucideIcon> = {
    help: HelpCircle,
    school: School,
    payments: Banknote,
    receipt_long: Receipt,
    directions_bus: Bus,
    event: CalendarDays,
    person: User,
    family_restroom: Users,
    report: Flag,
    support_agent: Headset,
    info: Info,
    calendar_month: Calendar,
    menu_book: BookOpen,
    sports_soccer: Trophy,
    restaurant: Utensils,
    checkroom: Shirt,
    medical_services: Stethoscope,
    security: Shield,
    call: Phone,
    chat: MessageCircle,
    assignment: ClipboardList,
    warning: AlertTriangle,
    star: Star,
    campaign: Megaphone,
    apps: LayoutGrid,
    badge: BadgeCheck,
    computer: Monitor,
    gavel: Gavel,
    how_to_reg: UserCheck,
    swap_horiz: ArrowLeftRight,
    savings: PiggyBank,
    schedule: Clock,
};

export function FlowIcon({ name, className }: { name?: string | null; className?: string }) {
    const Glyph = (name && FLOW_ICON_GLYPHS[name]) || HelpCircle;
    return <Glyph className={className} />;
}
